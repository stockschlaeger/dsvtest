-- Tabellen der neuen Anwendung in der Oracle-Altdatenbank (Präfix DSV_APP_, im Schema der Alttabellen).
-- Die Alttabellen bleiben unverändert. Entspricht db/app-schema.sql (PostgreSQL, Schema dsv_app);
-- Ja/Nein-Spalten als NUMBER(1) mit 0/1. Kompatibel ab Oracle 12c. Anlegen: npm run db:app

-- Anmeldungen (Logins) und ihre Zuordnung zu einer Altkennung (DSV_BENUTZERPROFIL.USER_ID); user_id NULL = nicht zugeordnet.
-- Lokale Anmeldung: Passwort als scrypt-Hash, Startpasswort muss geändert werden, vorübergehende Sperre nach Fehlversuchen.
CREATE TABLE dsv_app_anmeldung (
  login VARCHAR2(255) CONSTRAINT dsv_app_anmeldung_pk PRIMARY KEY,
  user_id VARCHAR2(30),
  name VARCHAR2(255),
  email VARCHAR2(255),
  gesperrt NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT dsv_app_anmeldung_gesperrt CHECK (gesperrt IN (0, 1)),
  erste_anmeldung TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  letzte_anmeldung TIMESTAMP WITH TIME ZONE,
  zugeordnet_von VARCHAR2(255),
  zugeordnet_am TIMESTAMP WITH TIME ZONE,
  vertretung_aktiv VARCHAR2(30),
  passwort_hash VARCHAR2(255),
  passwort_aendern NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT dsv_app_anmeldung_pw_aendern CHECK (passwort_aendern IN (0, 1)),
  passwort_gesetzt_am TIMESTAMP WITH TIME ZONE,
  fehlversuche NUMBER(5) DEFAULT 0 NOT NULL,
  gesperrt_bis TIMESTAMP WITH TIME ZONE
);

-- Sitzungen der lokalen Anmeldung; gespeichert wird nur der SHA-256 des Cookie-Werts
CREATE TABLE dsv_app_sitzung (
  token_hash CHAR(64) CONSTRAINT dsv_app_sitzung_pk PRIMARY KEY,
  login VARCHAR2(255) NOT NULL CONSTRAINT dsv_app_sitzung_login_fk REFERENCES dsv_app_anmeldung (login) ON DELETE CASCADE,
  erstellt TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  ablauf TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX dsv_app_sitzung_login ON dsv_app_sitzung (login);

-- Änderungsprotokoll der neuen Anwendung (wer hat wann was geändert); details als JSON-Text
CREATE TABLE dsv_app_protokoll (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT dsv_app_protokoll_pk PRIMARY KEY,
  zeitpunkt TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
  login VARCHAR2(255) NOT NULL,
  user_id VARCHAR2(30),
  objekt_typ VARCHAR2(30) NOT NULL,
  objekt_id VARCHAR2(100) NOT NULL,
  aktion VARCHAR2(40) NOT NULL,
  details CLOB
);
CREATE INDEX dsv_app_protokoll_objekt ON dsv_app_protokoll (objekt_typ, objekt_id);
